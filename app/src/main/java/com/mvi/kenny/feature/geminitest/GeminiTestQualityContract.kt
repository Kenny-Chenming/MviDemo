/**
 * ============================================================
 * GeminiTestQualityIntent — 用户操作意图
 * ================================================================
 * Sealed class representing all possible user intentions.
 */
sealed class GeminiTestQualityIntent {
    /** 加载仪表盘数据 */
    data object LoadDashboard : GeminiTestQualityIntent()

    /** 切换 Tab */
    data class SelectTab(val tab: TestQualityTab) : GeminiTestQualityIntent()

    /** 生成测试（指定源文件和框架） */
    data class GenerateTests(
        val sourceFile: String,
        val framework: TestFramework
    ) : GeminiTestQualityIntent()

    /** 评估指定测试文件的质量 */
    data class EvaluateQuality(val testFile: String) : GeminiTestQualityIntent()

    /** 保存测试规范模板 */
    data class SaveSpecTemplate(val template: TestSpecTemplate) : GeminiTestQualityIntent()

    /** 删除测试规范模板 */
    data class DeleteSpecTemplate(val templateId: String) : GeminiTestQualityIntent()

    /** 激活指定规范模板 */
    data class ActivateSpec(val templateId: String) : GeminiTestQualityIntent()

    /** 生成 CI/CD 配置 */
    data class GenerateCIConfig(val ciProvider: CIProvider) : GeminiTestQualityIntent()

    /** 分析测试盲区 */
    data object AnalyzeBlindSpots : GeminiTestQualityIntent()

    /** 刷新全部数据 */
    data object RefreshAll : GeminiTestQualityIntent()

    /** 配置覆盖策略 */
    data class UpdateCoverageStrategy(val strategy: CoverageStrategy) : GeminiTestQualityIntent()

    /** 导出质量报告 */
    data object ExportReport : GeminiTestQualityIntent()
}

