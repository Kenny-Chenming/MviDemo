/**
 * ============================================================
 * GeminiTestQualityEffect — 一次性副作用
 * ================================================================
 * One-time side effects triggered by ViewModel.
 */
sealed class GeminiTestQualityEffect {
    /** 显示操作结果提示 */
    data class ShowSnackbar(val message: String) : GeminiTestQualityEffect()

    /** 导出报告成功 */
    data class ExportReport(val filePath: String) : GeminiTestQualityEffect()

    /** 导航到测试文件 */
    data class NavigateToTestFile(val filePath: String) : GeminiTestQualityEffect()

    /** 运行 CI 验证 */
    data class RunCIValidation(val configYaml: String) : GeminiTestQualityEffect()

    /** 生成完成通知 */
    data class GenerationCompleted(val testFileName: String, val testCaseCount: Int) : GeminiTestQualityEffect()
}
