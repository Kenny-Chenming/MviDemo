/**
 * ============================================================
 * GeminiTestQualityState — 工具包页面状态
 * ================================================================
 * Immutable UI state — single source of truth for the entire toolkit.
 *
 * @param selectedTab Currently selected navigation tab
 * @param generatedTests List of Gemini-generated test files
 * @param qualityScore Aggregated quality metrics
 * @param coverageHeatmap Branch-level coverage data
 * @param selectedFramework Currently selected test framework
 * @param coverageStrategy Coverage strategy configuration
 * @param specTemplates Available test spec templates
 * @param activeSpec Currently active spec template
 * @param traceabilityRecords Source change → test impact records
 * @param blindSpots Detected uncovered code paths
 * @param ciConfig CI/CD configuration
 * @param isGenerating Whether test generation is in progress
 * @param generationProgress Generation progress (0.0-1.0)
 * @param error Error message if any operation failed
 */
data class GeminiTestQualityState(
    val selectedTab: TestQualityTab = TestQualityTab.Dashboard,
    val generatedTests: List<GeneratedTestFile> = emptyList(),
    val qualityScore: QualityScore = QualityScore(),
    val coverageHeatmap: Map<String, BranchCoverage> = emptyMap(),
    val selectedFramework: TestFramework = TestFramework.JUNIT5,
    val coverageStrategy: CoverageStrategy = CoverageStrategy(),
    val specTemplates: List<TestSpecTemplate> = emptyList(),
    val activeSpec: TestSpecTemplate? = null,
    val traceabilityRecords: List<TraceabilityRecord> = emptyList(),
    val blindSpots: List<BlindSpot> = emptyList(),
    val ciConfig: CIConfig = CIConfig(),
    val isGenerating: Boolean = false,
    val generationProgress: Float = 0f,
    val error: String? = null
) {
    /** Total generated test count / 生成测试文件总数 */
    val totalTests: Int get() = generatedTests.size

    /** Total test cases across all files / 所有文件的测试用例总数 */
    val totalTestCases: Int get() = generatedTests.sumOf { it.testCaseCount }

    /** Total missing risks across all files / 所有文件的遗漏风险总数 */
    val totalMissingRisks: Int get() = generatedTests.sumOf { it.missingRiskCount }

    /** Overall average quality score / 平均质量评分 */
    val averageQuality: Int
        get() = if (generatedTests.isEmpty()) 0
                else generatedTests.sumOf { it.qualityScore } / generatedTests.size
}

